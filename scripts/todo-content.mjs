// Generates TODO_CONTENT.md: every PLACEHOLDER, TODO_CONFIRM and NEEDS_NATIVE_REVIEW marker in the codebase,
// grouped by marker, with file:line and the surrounding text. Run: pnpm todo
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SCAN = ['src', 'public/CNAME', 'worker/src', 'worker/wrangler.toml', 'astro.config.mjs'];
const EXT = /\.(astro|ts|mjs|json|toml|css)$|CNAME$/;
const MARKERS = ['TODO_CONFIRM', 'PLACEHOLDER', 'NEEDS_NATIVE_REVIEW'];
// Lines that only *implement* the marker mechanism (not content to fill in).
const IGNORE = [
  /[!=]==\s*'TODO_CONFIRM'/,
  /includes\('TODO_CONFIRM'\)/,
  /True when a value is still a TODO_CONFIRM/,
  /marks answers awaiting founder confirmation/,
  /data-placeholder="PLACEHOLDER"/,
  /^\/\/ PLACEHOLDER visual for photos/,
];
const HELP = {
  TODO_CONFIRM: 'Facts to confirm or provide (contact details, domain, hours, unconfirmed FAQ answers).',
  PLACEHOLDER: 'Temporary content to replace with real content (curriculum details, prices, portraits).',
  NEEDS_NATIVE_REVIEW: 'Arabic text to be reviewed by a native speaker before launch.',
};

const files = [];
const walk = (p) => {
  const abs = join(ROOT, p);
  if (statSync(abs).isDirectory()) readdirSync(abs).forEach((f) => walk(join(p, f)));
  else if (EXT.test(p)) files.push(p);
};
SCAN.forEach(walk);

const hits = Object.fromEntries(MARKERS.map((m) => [m, []]));
for (const file of files.sort()) {
  readFileSync(join(ROOT, file), 'utf8')
    .split('\n')
    .forEach((line, i) => {
      for (const m of MARKERS) {
        if (!line.includes(m) || IGNORE.some((re) => re.test(line.trim()))) continue;
        // JSON FAQ entries: show the question this status belongs to.
        let text = line.trim();
        if (file.endsWith('.json') && /"status"/.test(line)) {
          const lines = readFileSync(join(ROOT, file), 'utf8').split('\n').slice(0, i).reverse();
          const q = lines.find((l) => /"q":/.test(l));
          text = `FAQ answer awaiting confirmation: ${q ? q.trim().replace(/^"q":\s*/, '').replace(/,$/, '') : '(question)'}`;
        }
        hits[m].push({ where: `${relative(ROOT, join(ROOT, file))}:${i + 1}`, text: text.slice(0, 160) });
      }
    });
}

let md = `# Content to fill in before launch

Generated by \`pnpm todo\` on ${new Date().toISOString().slice(0, 10)}. Re-run after edits; when a section is empty, it's done.

## Also (no marker in the code)

- **Partners**: add confirmed academies / institutions to \`src/data/partners.ts\` (logos in \`src/assets/partners/\`).
- **Photos**: real photos of the center and founders (see README → Photos).
- **Testimonials**: real quotes in \`src/data/testimonials.ts\`, then \`SHOW_TESTIMONIALS: true\`.
- **Stats**: confirmed numbers only, in \`src/data/stats.ts\`.
- **Vector logo** (optional): SVG / PDF master for print and very large screens.
`;
for (const m of MARKERS) {
  md += `\n## ${m} (${hits[m].length})\n\n${HELP[m]}\n\n`;
  md += hits[m].length ? hits[m].map((h) => `- \`${h.where}\`: ${h.text.replace(/\|/g, '\\|')}`).join('\n') + '\n' : '_Nothing left._\n';
}
writeFileSync(join(ROOT, 'TODO_CONTENT.md'), md);
console.log(MARKERS.map((m) => `${m}: ${hits[m].length}`).join(' · '));
